#!/usr/bin/env node
/**
 * Trump Offers — runtime environment generator.
 *
 * Reads process.env first, then `.env`, and writes `js/env.js`.
 * Only public values are ever written: never a service-role key.
 *
 * Usage: npm run env
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const envPath = resolve(root, '.env');

function parseEnv(text) {
  const out = {};
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq === -1) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    out[key] = value;
  }
  return out;
}

const fileEnv = existsSync(envPath) ? parseEnv(readFileSync(envPath, 'utf8')) : {};
const pick = (key, fallback = '') => process.env[key] ?? fileEnv[key] ?? fallback;

const SUPABASE_URL = pick('SUPABASE_URL').trim().replace(/\/$/, '');
const SUPABASE_ANON_KEY = pick('SUPABASE_ANON_KEY').trim();
const SITE_URL = pick('SITE_URL').trim().replace(/\/$/, '');
const DEMO_MODE = pick('DEMO_MODE', 'false').trim();
const SUPPORT_EMAIL = pick('SUPPORT_EMAIL', 'concierge@trumpoffers.com').trim();
const CARD_CONNECT_URL = pick('CARD_CONNECT_URL').trim();
const CARD_PROVIDER = pick('CARD_PROVIDER', 'provider').trim();
const BANK_VERIFICATION_URL = pick('BANK_VERIFICATION_URL').trim();

const configured = /^https:\/\/[a-z0-9-]+\.supabase\.co$/i.test(SUPABASE_URL) && SUPABASE_ANON_KEY.length >= 40;

if (!configured) {
  console.warn(
    '[env] Supabase is not configured. Set SUPABASE_URL and SUPABASE_ANON_KEY in .env for production.\n' +
      '      The local adapter is available only with DEMO_MODE=true.'
  );
}

const output = `/**
 * Trump Offers — public runtime configuration.
 * Generated by scripts/generate-env.mjs — do not edit by hand.
 *
 * The Supabase anon key is designed for browser use and is constrained by
 * Row Level Security. A service-role key must never appear here.
 */
window.TRUMP_ENV = ${JSON.stringify(
  {
    SUPABASE_URL: configured ? SUPABASE_URL : '',
    SUPABASE_ANON_KEY: configured ? SUPABASE_ANON_KEY : '',
    DEMO_MODE,
    SITE_URL,
    SUPPORT_EMAIL,
    CARD_CONNECT_URL,
    CARD_PROVIDER,
    BANK_VERIFICATION_URL,
  },
  null,
  2
)};
`;

writeFileSync(resolve(root, 'js/env.js'), output, 'utf8');
console.log(`[env] wrote js/env.js — ${configured ? 'Supabase mode available' : 'local development mode'}`);
